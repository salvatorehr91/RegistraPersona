CREATE TABLE  dbo.DTOESTUDIANTE
	(IDALUMNO INT IDENTITY (1,1) NOT NULL,
	VNOMBRE VARCHAR(50) NOT NULL,
	VAPATERNO VARCHAR(50) NOT NULL,
	VAMATERNO VARCHAR(50) NOT NULL,
	DNACIMIENTO DATE NOT NULL,
	VMATRICULA AS ('1' + REPLICATE('0',5-LEN(IDALUMNO)) + CAST(IDALUMNO AS INT)) PERSISTED,
	VSTATUS VARCHAR(2) NOT NULL) ON[PRIMARY]
COMMIT

