/*INSERTA*/
ALTER PROCEDURE SPINS_ESTUDIANTE(@VNOMBRE varchar(50), 
                    @VAPATERNO varchar(50),
                    @VAMATERNO varchar(50),
                    @DNACIMIENTO date,
                    @VSTATUS varchar(10))
AS 
BEGIN
    SET NOCOUNT ON;
    INSERT INTO DTOESTUDIANTE ([VNOMBRE],[VAPATERNO],[VAMATERNO],[DNACIMIENTO],[VSTATUS])
                    values (@VNOMBRE,@VAPATERNO,@VAMATERNO,@DNACIMIENTO,@VSTATUS)
    SELECT TOP 1 * FROM DTOESTUDIANTE
                WHERE VNOMBRE = @VNOMBRE
                AND VAPATERNO = @VAPATERNO AND VAMATERNO = @VAMATERNO
                AND DNACIMIENTO = @DNACIMIENTO ORDER BY IDALUMNO DESC
END;
 
/*ELIMINA*/
ALTER PROCEDURE SPDEL_ESTUDIANTE(@UNICO INTEGER,
                    @DNACIMIENTO DATE)
AS
BEGIN
    DELETE FROM DTOESTUDIANTE WHERE VMATRICULA = @UNICO AND DNACIMIENTO = @DNACIMIENTO;
    PRINT 'COMPLETADO';
END;
 
 
/*BUSQUEDA*/
ALTER PROCEDURE SPFIND_ESTUDIANTE(@VMATRICULA INTEGER)
AS
BEGIN
    SELECT * FROM DTOESTUDIANTE WHERE VMATRICULA = @VMATRICULA
END; 
 
/*ACTUALIZA*/
ALTER PROCEDURE SPUPD_ESTUDIANTE(@VNOMBRE varchar(50), 
                    @VAPATERNO varchar(50),
                    @VAMATERNO varchar(50),
                    @DNACIMIENTO date,
                    @VSTATUS varchar(10),
                    @VMATRICULA INTEGER)
AS
BEGIN
    UPDATE DTOESTUDIANTE 
        SET VNOMBRE = @VNOMBRE, VAPATERNO = @VAPATERNO, VAMATERNO = @VAMATERNO, DNACIMIENTO = @DNACIMIENTO, VSTATUS = @VSTATUS 
        WHERE VMATRICULA = @VMATRICULA;
    SELECT * FROM DTOESTUDIANTE WHERE VMATRICULA = @VMATRICULA;
END;
 
